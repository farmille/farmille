"""Excel `sources` シート → product_sources seed SQL 変換。

Farmille_BS_materials_DB_template_detailed_prompt.xlsx の `sources` シート
(company_name, product_name, source_type, source_title, source_url,
 source_rank, extracted_date, notes) を読み、product_sources テーブルへの
冪等 seed SQL (product 単位 DELETE → INSERT) を生成する。

product_id の解決は excel_to_seed_sql.py と同じ
「products.name + maker_profiles.company_name(正規化) の完全一致」。
未マッチ product は `WHERE ... IS NOT NULL` ガードで silent skip
(dev / prod でデータ差があっても安全に流せる)。

Usage:
    python backend/scripts/excel_to_sources_sql.py \
        --excel Farmille_BS_materials_DB_template_detailed_prompt.xlsx \
        --out docs/drafts/seed_product_sources_from_xlsx.sql \
        --skip-log docs/drafts/seed_product_sources_skip_log.md
"""

from __future__ import annotations

import argparse
import datetime as dt
import sys
from pathlib import Path
from typing import Any

import openpyxl

sys.path.insert(0, str(Path(__file__).resolve().parent))

from excel_to_seed_sql import (  # noqa: E402
    _product_select,
    is_blank,
    normalize_maker_name,
    sql_text,
)

VALID_RANKS = {"S", "A", "B", "C"}


def sql_date(value: Any) -> str:
    """date 列向け SQL リテラル。datetime / date / 'YYYY-MM-DD' 文字列を受ける。"""
    if value is None or value == "":
        return "NULL"
    if isinstance(value, dt.datetime):
        return f"'{value.date().isoformat()}'"
    if isinstance(value, dt.date):
        return f"'{value.isoformat()}'"
    s = str(value).strip()
    try:
        return f"'{dt.date.fromisoformat(s[:10]).isoformat()}'"
    except ValueError:
        return "NULL"


def load_sources(path: Path) -> list[dict[str, Any]]:
    wb = openpyxl.load_workbook(path, read_only=True, data_only=True)
    if "sources" not in wb.sheetnames:
        raise SystemExit("sources シートが見つかりません")
    ws = wb["sources"]
    it = ws.iter_rows(values_only=True)
    header = [str(c).strip() if c is not None else "" for c in next(it)]
    rows: list[dict[str, Any]] = []
    for raw in it:
        if raw is None or all(c is None for c in raw):
            continue
        rows.append(dict(zip(header, raw)))
    return rows


def build_sources_sql(rows: list[dict[str, Any]], skip_log: list[str]) -> str:
    sql_lines: list[str] = []
    sql_lines.append("-- =============================================================")
    sql_lines.append("-- product_sources: Excel sources シート")
    sql_lines.append("-- 各 product につき事前 DELETE → INSERT (冪等)")
    sql_lines.append("-- 未マッチ product は WHERE ガードで silent skip")
    sql_lines.append("-- Generated by backend/scripts/excel_to_sources_sql.py")
    sql_lines.append("-- =============================================================")
    sql_lines.append("")

    by_product: dict[tuple[str, str], list[dict[str, Any]]] = {}
    seen: set[tuple[str, str, str, str]] = set()
    for i, row in enumerate(rows, start=2):
        product_name = row.get("product_name")
        company_raw = row.get("company_name")
        url = row.get("source_url")
        if is_blank(product_name) or is_blank(company_raw):
            skip_log.append(f"- [sources row {i}] product_name or company_name 空 (skip)")
            continue
        if is_blank(url) or str(url).strip() in {"不明", "明記なし"}:
            skip_log.append(
                f"- [sources row {i}] source_url 空/不明 "
                f"(product={str(product_name)[:30]} / maker={company_raw}) (skip)"
            )
            continue
        key = (str(product_name), normalize_maker_name(company_raw))
        # 完全重複 (同一 product × source_type × url) は 1 件に収束
        dedupe_key = (*key, str(row.get("source_type") or ""), str(url).strip())
        if dedupe_key in seen:
            skip_log.append(
                f"- [sources row {i}] 重複行 (product={str(product_name)[:30]} / "
                f"type={row.get('source_type')}) (dedupe)"
            )
            continue
        seen.add(dedupe_key)
        by_product.setdefault(key, []).append(row)

    # 各 product の DELETE (冪等化)
    for product_name, normalized in by_product.keys():
        ps = _product_select(product_name, normalized)
        sql_lines.append(
            f"DELETE FROM product_sources WHERE product_id = {ps};"
        )
    sql_lines.append("")

    for (product_name, normalized), src_rows in by_product.items():
        ps = _product_select(product_name, normalized)
        for row in src_rows:
            rank_raw = row.get("source_rank")
            rank = (
                sql_text(rank_raw)
                if not is_blank(rank_raw) and str(rank_raw).strip() in VALID_RANKS
                else "NULL"
            )
            sql_lines.append(
                f"-- source for product '{str(product_name)[:30]}' / maker '{normalized}'"
            )
            sql_lines.append(
                "INSERT INTO product_sources "
                "(product_id, source_type, title, url, rank, extracted_date, notes)"
            )
            sql_lines.append("SELECT")
            sql_lines.append(
                f"  {ps}, {sql_text(row.get('source_type'))}, "
                f"{sql_text(row.get('source_title'))}, {sql_text(row.get('source_url'))}, "
                f"{rank}, {sql_date(row.get('extracted_date'))}, {sql_text(row.get('notes'))}"
            )
            sql_lines.append(f"WHERE {ps} IS NOT NULL;")
            sql_lines.append("")

    return "\n".join(sql_lines)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Excel sources シート → product_sources seed SQL 変換")
    p.add_argument("--excel", type=Path, required=True)
    p.add_argument("--out", type=Path, required=True)
    p.add_argument("--skip-log", type=Path, required=True)
    args = p.parse_args(argv)

    if not args.excel.exists():
        print(f"Excel が見つかりません: {args.excel}", file=sys.stderr)
        return 1

    rows = load_sources(args.excel)
    skip_log: list[str] = []
    sql = build_sources_sql(rows, skip_log)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(sql, encoding="utf-8")

    args.skip_log.parent.mkdir(parents=True, exist_ok=True)
    header = (
        "# Excel sources → product_sources 変換 skip 一覧\n\n"
        f"Generated: {dt.datetime.now().isoformat()}\n"
        f"Source: {args.excel}\n\n"
    )
    args.skip_log.write_text(header + "\n".join(skip_log) + "\n", encoding="utf-8")

    n_inserts = sql.count("INSERT INTO product_sources")
    print(
        f"[ok] wrote {args.out} ({len(rows)} rows → {n_inserts} inserts, "
        f"skip {len(skip_log)} → {args.skip_log})",
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
