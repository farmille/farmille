#!/usr/bin/env bash
# Claude Code cloud セッションの開始時に、ローカル Supabase と画面確認用のデモデータを用意する。
# 本番・ホスト型の Supabase には接続しない。

set -euo pipefail

if [ "${CLAUDE_CODE_REMOTE:-}" != "true" ]; then
  exit 0
fi

cd "$(dirname "${BASH_SOURCE[0]}")/../.."

readonly SUPABASE_CLI="supabase@2.120.0"
readonly DB_CONTAINER="supabase_db_farmille"
readonly LOCAL_API_URL="http://127.0.0.1:54321"
readonly ENV_LOCAL=".env.local"
readonly ENV_MARKER="# generated by tools/dev/claude-session-start.sh"

log() { printf '[claude-session-start] %s\n' "$*"; }
trap 'log "失敗しました（終了コード $?）: $BASH_COMMAND"' ERR

if ! docker info >/dev/null 2>&1; then
  log "Docker が止まっているので service docker start を実行します。"
  if ! start_output=$(service docker start 2>&1); then
    log "service docker start に失敗しました。"
    printf '%s\n' "$start_output"
    # cloud VM では init スクリプトの ulimit -Hn 524288 が権限不足で落ちるため、dockerd を直接起動する。
    log "dockerd を直接起動します（ログ: /var/log/dockerd.log）。"
    setsid nohup dockerd >/var/log/dockerd.log 2>&1 </dev/null &
  fi
  for _ in $(seq 1 30); do
    docker info >/dev/null 2>&1 && break
    sleep 2
  done
  if ! info_output=$(docker info 2>&1); then
    log "Docker を起動できませんでした。docker info の出力:"
    printf '%s\n' "$info_output"
    exit 1
  fi
fi
log "Docker は起動しています。"

pnpm install --frozen-lockfile >&2
pnpm exec playwright install --with-deps chromium >&2
log "依存関係と Playwright の Chromium を入れました。"

npx --yes "$SUPABASE_CLI" start -x studio,edge-runtime,realtime,imgproxy,logflare,vector >/dev/null
log "ローカル Supabase を起動しました。"

db_query() {
  docker exec -i "$DB_CONTAINER" psql -U postgres -d postgres -X -q -v ON_ERROR_STOP=1 -tA -c "$1"
}
db_run_file() {
  docker exec -i "$DB_CONTAINER" psql -U postgres -d postgres -X -q -v ON_ERROR_STOP=1 <"$1" >&2
}

has_material=$(db_query "select exists (select 1 from public.materials where name = 'Actibio X EVO53' and manufacturer_name = 'ICL JAPAN')")
if [ "$has_material" = "t" ]; then
  log "資材マスタは投入済みです。"
else
  db_run_file tools/migration/materials-v2-seed.sql
  log "資材マスタ（tools/migration/materials-v2-seed.sql）を投入しました。"
fi

has_home_demo=$(db_query "select exists (select 1 from public.reviews where id = '71000000-0000-4000-8000-000000000001')")
if [ "$has_home_demo" = "t" ]; then
  log "ホームのデモデータは投入済みです。"
else
  db_run_file tools/dev/seed-home-demo.sql
  log "ホームのデモデータ（tools/dev/seed-home-demo.sql）を投入しました。"
fi

status_json=$(npx --yes "$SUPABASE_CLI" status --output json 2>/dev/null)
api_url=$(jq -r '.API_URL // empty' <<<"$status_json")
if [ "$api_url" != "$LOCAL_API_URL" ]; then
  log "supabase status の API_URL が ${LOCAL_API_URL} ではありません（${api_url:-空}）。.env.local は書きません。"
  exit 1
fi
anon_key=$(jq -r '.ANON_KEY // empty' <<<"$status_json")
service_role_key=$(jq -r '.SERVICE_ROLE_KEY // empty' <<<"$status_json")
if [ -z "$anon_key" ] || [ -z "$service_role_key" ]; then
  log "supabase status から ANON_KEY または SERVICE_ROLE_KEY を取得できませんでした。"
  exit 1
fi

env_names=(
  NEXT_PUBLIC_SUPABASE_URL
  NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY
  SUPABASE_SECRET_KEY
  NEXT_PUBLIC_SITE_URL
  SMTP_URL
  MAIL_FROM
  AUTH_EMAIL_HOOK_SECRET
)
declare -A env_values=(
  [NEXT_PUBLIC_SUPABASE_URL]="$LOCAL_API_URL"
  [NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY]="$anon_key"
  [SUPABASE_SECRET_KEY]="$service_role_key"
  [NEXT_PUBLIC_SITE_URL]="http://localhost:3007"
  [SMTP_URL]="smtp://127.0.0.1:54325"
  [MAIL_FROM]="Farmille <noreply@example.test>"
  [AUTH_EMAIL_HOOK_SECRET]="v1,whsec_bG9jYWwtZmFybWlsbGUtZW1haWwtaG9vay10ZXN0LWtleQ=="
)

if [ -e "$ENV_LOCAL" ] && [ "$(head -n 1 "$ENV_LOCAL")" != "$ENV_MARKER" ]; then
  existing_url=$(grep -E '^NEXT_PUBLIC_SUPABASE_URL=' "$ENV_LOCAL" | tail -n 1 | cut -d= -f2- || true)
  log "既存の .env.local はこのスクリプトが作ったものではないので上書きしません。接続先: ${existing_url:-未設定}"
  log "ローカル Supabase へ向けるには .env.local を退避してから再実行してください。"
  exit 0
fi

(
  umask 077
  tmp_env=$(mktemp "${ENV_LOCAL}.XXXXXX")
  {
    printf '%s\n' "$ENV_MARKER"
    for name in "${env_names[@]}"; do
      printf '%s=%s\n' "$name" "${env_values[$name]}"
    done
  } >"$tmp_env"
  chmod 600 "$tmp_env"
  mv "$tmp_env" "$ENV_LOCAL"
)
log ".env.local をローカル Supabase 向けに書きました（権限 600）。"

if [ -n "${CLAUDE_ENV_FILE:-}" ]; then
  for name in "${env_names[@]}"; do
    printf 'export %s=%q\n' "$name" "${env_values[$name]}" >>"$CLAUDE_ENV_FILE"
  done
  log "同じ設定を CLAUDE_ENV_FILE に export しました。"
else
  log "CLAUDE_ENV_FILE が無いので export は省きました。"
fi

# 既存のボリュームから起動した DB には、後から足された migration が入らない。
bash tools/dev/check-migrations.sh
